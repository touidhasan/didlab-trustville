#!/usr/bin/env node
/**
 * Generate contracts/src/PoseidonT3.sol from circomlibjs.
 *
 *   node scripts/gen-poseidon.mjs
 *
 * Module 16's Merkle tree must hash the same way on chain as it does inside the circuit, or
 * a proof that is correct will verify against a root the contract never computed. That rules
 * out keccak256: hashing it inside a circuit costs on the order of 150,000 constraints,
 * against Poseidon's ~240. Poseidon exists because SNARK-friendliness is a real constraint
 * on cryptography, not a footnote.
 *
 * There is no readable Solidity implementation of Poseidon worth trusting -- the reference
 * one is generated EVM assembly, and hand-porting a hash function is how you get a subtle
 * incompatibility that only shows up as "proof verifies off chain, fails on chain". So this
 * writes circomlib's own generated bytecode into a constant and deploys it verbatim. It is
 * the same thing Tornado and Semaphore do.
 *
 * Regenerate it if circomlib's version changes, and rerun the tests: the tree's hash
 * function changing means every existing root is wrong.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { poseidonContract } = require('circomlibjs');

const creationCode = poseidonContract.createCode(2);
const hex = creationCode.startsWith('0x') ? creationCode.slice(2) : creationCode;

const sol = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.24;

/// @title Poseidon(2) for module 16's Merkle tree
/// @notice GENERATED by scripts/gen-poseidon.mjs from circomlib. Do not edit by hand.
/// @dev    The contract below is circomlib's own compiled Poseidon, embedded as creation
///         bytecode and deployed verbatim.
///
///         Why not write it in Solidity? Because the tree must hash EXACTLY as the circuit
///         does. A hand-port that is subtly wrong produces the most miserable class of bug
///         in this field: proofs that verify off chain and fail on chain, with nothing in
///         either place to point at. Using the reference implementation removes the question.
///
///         Why Poseidon rather than keccak256? Keccak inside a SNARK costs roughly 150,000
///         constraints; Poseidon costs about 240. The hash function has to be chosen for the
///         proving system, which is one of the first real surprises in zero-knowledge work.
interface IPoseidonT3 {
    function poseidon(uint256[2] calldata input) external pure returns (uint256);
}

library PoseidonT3 {
    bytes internal constant CREATION_CODE = hex"${hex}";

    /// Deploy the hasher. Called once, from the deployment script.
    function deploy() internal returns (IPoseidonT3 hasher) {
        bytes memory code = CREATION_CODE;
        address addr;
        assembly {
            addr := create(0, add(code, 0x20), mload(code))
        }
        require(addr != address(0), "PoseidonT3: deployment failed");
        hasher = IPoseidonT3(addr);
    }
}
`;

writeFileSync(new URL('../contracts/src/PoseidonT3.sol', import.meta.url), sol);
console.log(`wrote contracts/src/PoseidonT3.sol (${hex.length / 2} bytes of creation code)`);
